import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const sourcePath = path.resolve(
  __dirname,
  "../../rooms/data/outreach/vancouver-host-space-draft-packet-2026-06-13.csv",
);
const outputPath = path.resolve(__dirname, "../src/data/roomsVancouverBusinessSeeds.ts");

const categoryMap = {
  cultural_space: {
    category: "Cultural space",
    segment: "Venue and cultural partner",
  },
  restaurant_bar: {
    category: "Restaurant / bar",
    segment: "Hospitality and hosted-visit partner",
  },
  event_venue: {
    category: "Event venue",
    segment: "Private-group and hosted-visit partner",
  },
  hotel_event_space: {
    category: "Hotel",
    segment: "Guest services and event-space partner",
  },
  coworking_space: {
    category: "Coworking space",
    segment: "Founder event and gathering partner",
  },
};

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;

  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    const next = text[index + 1];

    if (char === '"') {
      if (inQuotes && next === '"') {
        field += '"';
        index += 1;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }

    if (char === "," && !inQuotes) {
      row.push(field);
      field = "";
      continue;
    }

    if ((char === "\n" || char === "\r") && !inQuotes) {
      if (char === "\r" && next === "\n") {
        index += 1;
      }
      row.push(field);
      field = "";
      if (row.some((value) => value.length > 0)) {
        rows.push(row);
      }
      row = [];
      continue;
    }

    field += char;
  }

  if (field.length > 0 || row.length > 0) {
    row.push(field);
    if (row.some((value) => value.length > 0)) {
      rows.push(row);
    }
  }

  return rows;
}

function escapeString(value) {
  return value.replace(/\\/g, "\\\\").replace(/'/g, "\\'");
}

function formatSeed(seed) {
  const keys = [
    "businessName",
    "neighborhood",
    "category",
    "segment",
    "sourceUrl",
    "website",
    "email",
    "sourceProof",
    "notes",
    "contactConfidence",
    "donorSourceLabel",
  ];

  return [
    "  {",
    ...keys.map((key) => `    ${key}: '${escapeString(seed[key])}',`),
    "  },",
  ].join("\n");
}

function normalizeRow(row) {
  const details = categoryMap[row.category] || {
    category: "Local business",
    segment: "Vancouver business partner",
  };
  const officialUrl = row.officialUrl || row.sourceUrl || "";
  const sourceUrl = row.sourceUrl || officialUrl;
  const sourcedFromSecondaryListing = Boolean(sourceUrl && officialUrl && sourceUrl !== officialUrl);

  return {
    businessName: row.name,
    neighborhood: "",
    category: details.category,
    segment: details.segment,
    sourceUrl: officialUrl,
    website: officialUrl,
    email: row.to,
    sourceProof: sourcedFromSecondaryListing
      ? "Rooms donor research from the reviewed Vancouver host-space packet. Official site is linked, but the donor packet sourced this contact through a secondary public listing that still needs re-verification before any send."
      : "Rooms donor research from the reviewed Vancouver host-space packet using the official public business source.",
    notes: sourcedFromSecondaryListing
      ? `Imported from the Rooms reviewed Vancouver host-space packet for local CityAtlas review only. The original donor packet paired this row with a secondary public listing (${sourceUrl}) and marked it for manual review before any send. Original donor blocker: ${row.sendBlockers}`
      : `Imported from the Rooms reviewed Vancouver host-space packet for local CityAtlas review only. Original donor blocker: ${row.sendBlockers}`,
    contactConfidence: sourcedFromSecondaryListing ? "medium" : "high",
    donorSourceLabel: sourcedFromSecondaryListing
      ? "Rooms host-space donor (official site plus secondary public listing)"
      : "Rooms host-space donor (official public source)",
  };
}

const csv = await fs.readFile(sourcePath, "utf8");
const [header, ...rows] = parseCsv(csv);
const keys = header.map((value) => value.trim());
const seeds = rows.map((values) =>
  normalizeRow(
    Object.fromEntries(keys.map((key, index) => [key, values[index] ?? ""])),
  ),
);

const fileContents = `// Generated by scripts/sync-rooms-vancouver-business-seeds.mjs
// Source: ../rooms/data/outreach/vancouver-host-space-draft-packet-2026-06-13.csv

export const roomsVancouverBusinessSeeds = [
${seeds.map(formatSeed).join("\n")}
];
`;

await fs.writeFile(outputPath, fileContents, "utf8");

console.log(
  JSON.stringify(
    {
      ok: true,
      sourcePath,
      outputPath,
      seedCount: seeds.length,
    },
    null,
    2,
  ),
);
