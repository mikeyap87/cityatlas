import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const sourceDir = path.resolve(
  __dirname,
  "../../roam-relaxation/fixtures/provider-discovery",
);
const outputPath = path.resolve(__dirname, "../src/data/roamPublicBusinessWaveSeeds.ts");

const prospectTypeMap = {
  chair_massage: {
    category: "Wellness",
    segment: "Corporate wellness partner",
  },
  mobile_massage: {
    category: "Wellness",
    segment: "Mobile massage and recovery partner",
  },
  mobile_rmt: {
    category: "Wellness",
    segment: "Mobile massage and recovery partner",
  },
};

function escapeString(value) {
  return String(value || "").replace(/\\/g, "\\\\").replace(/'/g, "\\'");
}

function slugify(value) {
  return String(value || "")
    .trim()
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function formatSeed(seed) {
  const keys = [
    "cityKey",
    "cityName",
    "businessName",
    "neighborhood",
    "category",
    "segment",
    "sourceUrl",
    "website",
    "email",
    "contactPath",
    "contactPathType",
    "contactReadiness",
    "sourceProof",
    "notes",
    "contactConfidence",
    "donorSourceLabel",
  ];

  return [
    "  {",
    ...keys.map((key) => `    ${key}: '${escapeString(seed[key])}',`),
    "  },",
  ].join("\n");
}

function getProspectDetails(prospectType) {
  return prospectTypeMap[prospectType] || {
    category: "Wellness",
    segment: "Wellness partner",
  };
}

function normalizeSeed(cityName, item) {
  const details = getProspectDetails(item.prospectType);
  const email = String(item.email || "").trim().toLowerCase();
  const phone = String(item.phone || "").trim();
  const sourceUrl = String(item.sourceUrl || item.website || "").trim();
  const website = String(item.website || sourceUrl).trim();
  const serviceAreas = String(item.serviceAreas || "").trim();
  const fitNotes = String(item.fitNotes || "").trim();
  const sourceEvidence = String(item.sourceEvidence || "").trim();
  const contactPath = email ? `mailto:${email}` : phone ? `tel:${phone.replace(/\s+/g, "")}` : "";
  const contactPathType = email
    ? "direct_email"
    : phone
      ? "phone_or_text"
      : "needs_manual_lookup";
  const contactReadiness = email
    ? "email_ready"
    : phone
      ? "contact_path_ready"
      : "needs_research";
  const contactConfidence = email ? "high" : phone ? "medium" : "low";
  const donorSourceLabel = email
    ? "Roam public business wave donor (official public contact)"
    : phone
      ? "Roam public business wave donor (official public phone path)"
      : "Roam public business wave donor (needs manual contact review)";

  const notesParts = [
    "Imported from the saved Roam public business wave fixture for local CityAtlas review only.",
    serviceAreas ? `Public service area note: ${serviceAreas}.` : "",
    fitNotes ? `Fit note: ${fitNotes}` : "",
    phone ? `Public phone found on source page: ${phone}.` : "",
    "Re-verify the official contact path before any outreach or public claim.",
  ].filter(Boolean);

  return {
    cityKey: slugify(cityName),
    cityName,
    businessName: String(item.businessName || "").trim(),
    neighborhood: cityName,
    category: details.category,
    segment: details.segment,
    sourceUrl,
    website,
    email,
    contactPath,
    contactPathType,
    contactReadiness,
    sourceProof: sourceEvidence || "Saved Roam provider-discovery fixture using an official public business source.",
    notes: notesParts.join(" "),
    contactConfidence,
    donorSourceLabel,
  };
}

const files = (await fs.readdir(sourceDir))
  .filter((fileName) => fileName.endsWith("-public-business-wave.json"))
  .sort();

const sources = [];
const seeds = [];

for (const fileName of files) {
  const sourcePath = path.join(sourceDir, fileName);
  const raw = await fs.readFile(sourcePath, "utf8");
  const fixture = JSON.parse(raw);
  const cityName = String(fixture.city || "").trim();
  const items = Array.isArray(fixture.items) ? fixture.items : [];

  if (!cityName || items.length === 0) {
    continue;
  }

  sources.push(`// - ../roam-relaxation/fixtures/provider-discovery/${fileName}`);
  seeds.push(...items.map((item) => normalizeSeed(cityName, item)));
}

const fileContents = `// Generated by scripts/sync-roam-public-business-wave-seeds.mjs
// Sources:
${sources.join("\n")}

export const roamPublicBusinessWaveSeeds = [
${seeds.map(formatSeed).join("\n")}
];
`;

await fs.writeFile(outputPath, fileContents, "utf8");

console.log(
  JSON.stringify(
    {
      ok: true,
      sourceDir,
      outputPath,
      sourceCount: files.length,
      seedCount: seeds.length,
    },
    null,
    2,
  ),
);
