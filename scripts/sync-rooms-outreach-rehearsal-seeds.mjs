async function loadCsvRows(sourcePath) {
  const csv = await fs.readFile(sourcePath, "utf8");
  const [header, ...rows] = parseCsv(csv);
  const keys = header.map((value) => value.trim());
  return rows.map((values) => Object.fromEntries(keys.map((key, index) => [key, values[index] ?? ""])));
}

