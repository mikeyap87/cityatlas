const metricDefinitions = [
  {
    label: "Inbound replies reviewed",
    regex: /^- New inbound CityAtlas replies reviewed:\s*(\d+)/m,
    detail: "Messages read and triaged from real businesses.",
  },
  {
    label: "Live replies sent",
    regex: /^- Live replies sent:\s*(\d+)/m,
    detail: "Clear follow-ups already sent by CityAtlas.",
  },
  {
    label: "Active conversations",
    regex: /^- Interested conversations now active:\s*(\d+)/m,
    detail: "Businesses still in a real back-and-forth now.",
  },
  {
    label: "Hosted-offer asks made",
    regex: /^- Active conversations with hosted-offer ask made:\s*(\d+)/m,
    detail: "Hosted meal or service asks already made when the fit was clear.",
  },
];

function extractMatch(markdown, regex, label) {
  const match = markdown.match(regex);
  if (!match?.[1]) {
    throw new Error(`Could not find ${label} in ${BUSINESS_REPLY_STATUS_SOURCE_PATH}`);
  }
  return match[1].trim();
}

function extractSectionBody(markdown, heading) {
  const headingPattern = new RegExp(`^## ${heading}\\s*$`, "m");
  const headingMatch = headingPattern.exec(markdown);
  if (!headingMatch) {
    throw new Error(`Could not find section "${heading}" in ${BUSINESS_REPLY_STATUS_SOURCE_PATH}`);
  }

  const sectionStart = headingMatch.index + headingMatch[0].length;
  const remainder = markdown.slice(sectionStart).trimStart();
  const nextHeadingMatch = /^##\s+/m.exec(remainder);
  const rawBody = nextHeadingMatch
    ? remainder.slice(0, nextHeadingMatch.index).trim()
    : remainder.trim();
  const body = rawBody.split("<!--")[0]?.trim() ?? "";

  if (!body) {
    throw new Error(`Section "${heading}" in ${BUSINESS_REPLY_STATUS_SOURCE_PATH} was empty.`);
  }

  return body;
}

export function buildBusinessReplyStatusSnapshot(markdown) {
  const lastUpdated = extractMatch(markdown, /^Last updated:\s*([0-9-]+)/m, "last updated date");
  const metrics = metricDefinitions.map((definition) => ({
    label: definition.label,
    value: Number(extractMatch(markdown, definition.regex, definition.label)),
    detail: definition.detail,
  }));
  const [inboundRepliesReviewed, liveRepliesSent, activeConversations, hostedOfferAsksMade] = metrics;
  const currentReplyRule = extractSectionBody(markdown, "Current Reply Rule")
    .replace(/\s+/g, " ")
    .trim();

  return {
    lastUpdated,
    sourcePath: BUSINESS_REPLY_STATUS_SOURCE_RELATIVE_PATH,
    summary:
      `CityAtlas has already reviewed ${inboundRepliesReviewed.value} real inbound business replies, `
      + `sent ${liveRepliesSent.value} live follow-ups where the intent was clear, `
      + "and kept the first step on the free-review path.",
    metrics,
    nextStep:
      hostedOfferAsksMade.value > 0 || activeConversations.value > 0
        ? "The next move is still a fit note, short call, or hosted visit only when the match is clear."
        : "The next move is still a fit note or short call only when the match is clear.",
    boundary:
      `${currentReplyRule} Nothing public or paid goes live from the first reply alone, `
      + "and CityAtlas can still say the fit is weak.",
  };
}

