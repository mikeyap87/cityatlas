import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const roomsResearchDir = path.resolve(__dirname, "../../rooms/docs/research");
const cityConnectorSourcePath = path.join(roomsResearchDir, "rooms-city-connectors.json");
const namedConnectorSourcePath = path.join(
  roomsResearchDir,
  "rooms-vancouver-named-connectors.json",
);
const cityConnectorOutputPath = path.resolve(
  __dirname,
  "../src/data/roomsCityConnectorSeeds.ts",
);
const namedConnectorOutputPath = path.resolve(
  __dirname,
  "../src/data/roomsVancouverNamedConnectorSeeds.ts",
);

function escapeString(value) {
  return String(value || "").replace(/\\/g, "\\\\").replace(/'/g, "\\'");
}

function slugify(value) {
  return String(value || "")
    .trim()
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function formatSeed(seed, keys) {
  return [
    "  {",
    ...keys.map((key) => `    ${key}: '${escapeString(seed[key])}',`),
    "  },",
  ].join("\n");
}

const cityConnectorKeys = [
  "cityKey",
  "cityName",
  "connectorName",
  "eventType",
  "audience",
  "whyItMatters",
  "publicContactPath",
  "confidence",
  "sourceUrl",
  "accessDate",
  "notes",
];

const namedConnectorKeys = [
  "cityKey",
  "cityName",
  "laneId",
  "laneLabel",
  "name",
  "role",
  "organization",
  "whyItMatters",
  "bestPublicContactPath",
  "confidence",
  "sourceUrl",
  "accessDate",
  "notes",
];

const cityConnectorSource = JSON.parse(await fs.readFile(cityConnectorSourcePath, "utf8"));
const namedConnectorSource = JSON.parse(await fs.readFile(namedConnectorSourcePath, "utf8"));

const cityConnectorSeeds = cityConnectorSource.map((row) => ({
  cityKey: slugify(row.city),
  cityName: row.city,
  connectorName: row.connector,
  eventType: row.event_type,
  audience: row.audience,
  whyItMatters: row.why_it_matters_to_rooms,
  publicContactPath: row.public_contact_path,
  confidence: row.confidence,
  sourceUrl: row.source_url,
  accessDate: row.access_date,
  notes: row.notes,
}));

const namedConnectorSeeds = namedConnectorSource.map((row) => ({
  cityKey: "vancouver",
  cityName: "Vancouver",
  laneId: row.lane_id,
  laneLabel: row.lane_label,
  name: row.name,
  role: row.role,
  organization: row.organization,
  whyItMatters: row.why_it_matters,
  bestPublicContactPath: row.best_public_contact_path,
  confidence: row.confidence,
  sourceUrl: row.source_url,
  accessDate: row.access_date,
  notes: row.notes,
}));

const cityConnectorFileContents = `// Generated by scripts/sync-rooms-connector-seeds.mjs
// Source: ../rooms/docs/research/rooms-city-connectors.json

export const roomsCityConnectorSeeds = [
${cityConnectorSeeds.map((seed) => formatSeed(seed, cityConnectorKeys)).join("\n")}
];
`;

const namedConnectorFileContents = `// Generated by scripts/sync-rooms-connector-seeds.mjs
// Source: ../rooms/docs/research/rooms-vancouver-named-connectors.json

export const roomsVancouverNamedConnectorSeeds = [
${namedConnectorSeeds.map((seed) => formatSeed(seed, namedConnectorKeys)).join("\n")}
];
`;

await fs.writeFile(cityConnectorOutputPath, cityConnectorFileContents, "utf8");
await fs.writeFile(namedConnectorOutputPath, namedConnectorFileContents, "utf8");

console.log(
  JSON.stringify(
    {
      ok: true,
      cityConnectorSourcePath,
      namedConnectorSourcePath,
      cityConnectorOutputPath,
      namedConnectorOutputPath,
      cityConnectorSeedCount: cityConnectorSeeds.length,
      namedConnectorSeedCount: namedConnectorSeeds.length,
    },
    null,
    2,
  ),
);
